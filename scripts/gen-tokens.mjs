#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { palette } from '../packages/shared/src/tokens.ts';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const outDir = path.join(rootDir, 'apps', 'admin', 'src', 'app');

fs.mkdirSync(outDir, { recursive: true });

function formatPaletteVars(p) {
  return [
    `  --bg: ${p.bg};`,
    `  --surface: ${p.surface};`,
    `  --surface2: ${p.surface2};`,
    `  --raised: ${p.raised};`,
    `  --border: ${p.border};`,
    `  --border-strong: ${p.borderStrong};`,
    `  --fg: ${p.fg};`,
    `  --muted: ${p.muted};`,
    `  --subtle: ${p.subtle};`,
    `  --primary: ${p.primary};`,
    `  --on-primary: ${p.onPrimary};`,
    `  --ok: ${p.ok};`,
    `  --warn: ${p.warn};`,
    `  --bad: ${p.bad};`,
  ].join('\n');
}

const content = `/* GENERATED by scripts/gen-tokens.mjs. Do not edit. */
@theme {
  --color-bg: var(--bg);
  --color-surface: var(--surface);
  --color-surface2: var(--surface2);
  --color-raised: var(--raised);
  --color-border: var(--border);
  --color-border-strong: var(--border-strong);
  --color-fg: var(--fg);
  --color-muted: var(--muted);
  --color-subtle: var(--subtle);
  --color-primary: var(--primary);
  --color-on-primary: var(--on-primary);
  --color-ok: var(--ok);
  --color-warn: var(--warn);
  --color-bad: var(--bad);
  --radius-card: 26px;
  --radius-sheet: 28px;
  --font-display: var(--font-archivo);
  --font-accent: var(--font-fraunces);
  --font-body: var(--font-figtree);
  --font-mono: var(--font-martian);
}

:root {
${formatPaletteVars(palette.dark)}
}

:root[data-theme="day"] {
${formatPaletteVars(palette.day)}
}

@media (prefers-color-scheme: light) {
  :root[data-theme="system"] {
${formatPaletteVars(palette.day)}
  }
}
`;

const targetFile = path.join(outDir, 'tokens.css');
fs.writeFileSync(targetFile, content, 'utf8');
console.warn('[tokens] Generated apps/admin/src/app/tokens.css');


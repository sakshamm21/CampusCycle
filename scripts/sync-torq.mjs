#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const isCheck = process.argv.includes('--check');

const HEADER = '// GENERATED by scripts/sync-torq.mjs. Do not edit.\n';

const filesToSync = new Map(); // targetRelPath -> contentString

// 1. packages/torq/src/** -> supabase/functions/_shared/vendor/torq/
const torqSrcDir = path.join(rootDir, 'packages', 'torq', 'src');
if (fs.existsSync(torqSrcDir)) {
  function walkTorqSrc(dir, base) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      const rel = path.join(base, entry.name);
      if (entry.isDirectory()) {
        walkTorqSrc(full, rel);
      } else if (entry.isFile() && entry.name.endsWith('.ts')) {
        let content = fs.readFileSync(full, 'utf8');
        content = HEADER + content;
        filesToSync.set(path.join('supabase', 'functions', '_shared', 'vendor', 'torq', rel), content);
      }
    }
  }
  walkTorqSrc(torqSrcDir, '');
}

// 2. packages/torq/prompts/** -> supabase/functions/_shared/vendor/torq/prompts/
const promptsDir = path.join(rootDir, 'packages', 'torq', 'prompts');
if (fs.existsSync(promptsDir)) {
  for (const entry of fs.readdirSync(promptsDir, { withFileTypes: true })) {
    if (entry.isFile()) {
      const full = path.join(promptsDir, entry.name);
      const raw = fs.readFileSync(full, 'utf8');
      const escaped = raw.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
      const outTs = HEADER + `export default \`${escaped}\`;\n`;
      const outName = entry.name.endsWith('.md') ? entry.name.replace(/\.md$/, '.ts') : `${entry.name}.ts`;
      filesToSync.set(
        path.join('supabase', 'functions', '_shared', 'vendor', 'torq', 'prompts', outName),
        outTs,
      );
    }
  }
}

// 3. packages/shared/src/errors.ts, strings/en.ts, constants.ts, qr.ts -> supabase/functions/_shared/vendor/shared/
const sharedFiles = ['errors.ts', path.join('strings', 'en.ts'), 'constants.ts', 'qr.ts'];
for (const rel of sharedFiles) {
  const full = path.join(rootDir, 'packages', 'shared', 'src', rel);
  if (fs.existsSync(full)) {
    let content = fs.readFileSync(full, 'utf8');
    // Rewrite imports from './x' to './x.ts'
    content = content.replace(/from\s+['"](\.[^'"]*?)['"]/g, (match, p1) => {
      if (p1.endsWith('.ts') || p1.endsWith('.json')) return match;
      return `from '${p1}.ts'`;
    });
    content = HEADER + content;
    filesToSync.set(path.join('supabase', 'functions', '_shared', 'vendor', 'shared', rel), content);
  }
}

let hasDiff = false;

if (isCheck) {
  for (const [relPath, expected] of filesToSync.entries()) {
    const fullPath = path.join(rootDir, relPath);
    if (!fs.existsSync(fullPath)) {
      console.error(`[sync-torq:check] Missing file: ${relPath}`);
      hasDiff = true;
    } else {
      const existing = fs.readFileSync(fullPath, 'utf8');
      if (existing !== expected) {
        console.error(`[sync-torq:check] File differs: ${relPath}`);
        hasDiff = true;
      }
    }
  }

  if (hasDiff) {
    console.error('[sync-torq:check] Files out of sync. Run pnpm torq:sync to fix.');
    process.exit(1);
  } else {
    console.warn('[sync-torq:check] All vendor files are in sync.');
    process.exit(0);
  }
} else {
  // Sync mode: write files
  let count = 0;
  for (const [relPath, content] of filesToSync.entries()) {
    const fullPath = path.join(rootDir, relPath);
    fs.mkdirSync(path.dirname(fullPath), { recursive: true });
    fs.writeFileSync(fullPath, content, 'utf8');
    count++;
  }
  console.warn(`[sync-torq] Synced ${count} vendor files.`);
}

import { describe, it, expect, beforeAll } from 'vitest';
import { createAuthenticatedClient, type SupabaseClient } from './helpers';

describe('110: QR Code Generation & Validation', () => {
  let demoRiderClient: SupabaseClient;
  let demoAdminClient: SupabaseClient;

  beforeAll(async () => {
    demoRiderClient = await createAuthenticatedClient('demo-rider@example.com');
    demoAdminClient = await createAuthenticatedClient('demo-admin@example.com');
  });

  it('pass QR generated by get_my_pass_qr scans successfully by admin', async () => {
    const { data: qrData, error: qrErr } = await demoRiderClient.rpc('get_my_pass_qr');
    expect(qrErr).toBeNull();
    expect(qrData?.ok).toBe(true);
    expect(qrData?.payload).toBeDefined();

    const { data: scanData, error: scanErr } = await demoAdminClient.rpc('admin_scan_pass', {
      p_payload: qrData.payload,
    });
    expect(scanErr).toBeNull();
    expect(scanData?.ok).toBe(true);
    expect(scanData?.holder?.name).toBe('Aanya Sharma');
  });

  it('admin_scan_pass rejects tampered signature with CC_BAD_QR', async () => {
    const { data: qrData } = await demoRiderClient.rpc('get_my_pass_qr');
    const tamperedPayload = qrData.payload.slice(0, -5) + 'xxxxx';

    const { data } = await demoAdminClient.rpc('admin_scan_pass', {
      p_payload: tamperedPayload,
    });
    expect(data?.ok).toBe(false);
    expect(data?.code).toBe('CC_BAD_QR');
  });

  it('admin_scan_pass rejects expired time window with CC_PASS_QR_EXPIRED or CC_BAD_QR', async () => {
    // Modify timestamp parameter t= to an expired window
    const url = new URL(
      'campuscycle://p/11111111-1111-4111-8111-111111111111?t=100000&s=1234567890123456789012',
    );
    const { data } = await demoAdminClient.rpc('admin_scan_pass', {
      p_payload: url.toString(),
    });
    expect(data?.ok).toBe(false);
    expect(['CC_PASS_QR_EXPIRED', 'CC_BAD_QR']).toContain(data?.code);
  });
});
